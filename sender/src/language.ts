let language =
    navigator.languages
        .find((value) => /^(en|ru)(-|$)/i.test(value))
        ?.slice(0, 2)
        .toLowerCase() ?? "en";
try {
    const saved = localStorage.getItem("sendtv.language");
    if (saved === "en" || saved === "ru") language = saved;
} catch {
    /* Language selection works without storage. */
}
const normalize = (value: string) => value.replace(/\s+/g, " ").trim();
function translate(value: string) {
    if (language !== "ru") return value;
    const code = /^Compare code (\d{6}) on the TV\.$/.exec(value);
    if (code) return `Сравните код ${code[1]} на телевизоре.`;
    return russian[normalize(value)] ?? value;
}
const dynamic = new Map<HTMLElement, string>();
export function setText(element: HTMLElement, value: string) {
    dynamic.set(element, value);
    element.textContent = translate(value);
}
const nodes = new Map<Text, string>();
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
    const node = walker.currentNode as Text;
    if (
        node.parentElement?.closest(
            "script, style, #status, #error, #verification, #receiver, option",
        )
    )
        continue;
    if (normalize(node.data)) nodes.set(node, normalize(node.data));
}
const selector = document.getElementById("language") as HTMLSelectElement;
const name = document.getElementById("name") as HTMLInputElement;
const device = document.querySelector<HTMLElement>(".device")!;
const title = document.title;
function update() {
    document.documentElement.lang = language;
    document.title = translate(title);
    nodes.forEach((original, node) => {
        node.data = translate(original);
    });
    dynamic.forEach((original, element) => {
        element.textContent = translate(original);
    });
    device.setAttribute("aria-label", translate("Selected receiver"));
    selector.value = language;
}
name.value = translate(name.defaultValue);
document.getElementById("receiver")!.textContent = translate("Your TV");
update();
selector.addEventListener("change", () => {
    language = selector.value === "ru" ? "ru" : "en";
    try {
        localStorage.setItem("sendtv.language", language);
    } catch {
        /* Optional preference. */
    }
    update();
});
